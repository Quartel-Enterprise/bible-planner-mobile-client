package com.quare.bibleplanner.ui.theme.font

/**
 * The typefaces the reader offers for the bible text. [SYSTEM] renders with the platform's own
 * sans-serif — Roboto on Android — and is the only entry that ships no font file.
 */
enum class ReaderFont {
    LORA,
    LITERATA,
    GARAMOND,
    CRIMSON,
    BITTER,
    SYSTEM,
    NUNITO,
    ATKINSON,
    DYSLEXIC,
}
